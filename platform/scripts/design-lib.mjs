// Shared helpers for the design gate (check-design.mjs), the colours generator (gen-colors.mjs)
// and tests/design.test.mjs. No dependencies.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const TOKENS = path.join(ROOT, 'src/design/tokens.css');
export const COLORS_JS = path.join(ROOT, 'src/design/colors.js');

// Custom properties of the first :root block (the reduced-motion override is ignored).
export function parseTokens(css = readFileSync(TOKENS, 'utf8')) {
  const body = css.replace(/\/\*[\s\S]*?\*\//g, '').match(/:root\s*\{([\s\S]*?)\}/)[1];
  const out = {};
  for (const m of body.matchAll(/(--az-[\w-]+)\s*:\s*([^;]+);/g)) out[m[1]] = m[2].trim();
  return out;
}

const COLOR_RE = /^(#[0-9a-f]{3,8}|rgba?\([^)]*\))$/i;
export const camel = name => name.replace(/^--az-/, '').replace(/-(\w)/g, (_, c) => c.toUpperCase());

// Every token whose value is a single colour literal, keyed in camelCase (--az-band-tendu -> bandTendu).
export function colorTokens(tokens = parseTokens()) {
  return Object.fromEntries(Object.entries(tokens).filter(([, v]) => COLOR_RE.test(v)).map(([k, v]) => [camel(k), v]));
}

export function colorsSource(tokens = parseTokens()) {
  const c = colorTokens(tokens);
  const lines = Object.entries(c).map(([k, v]) => `  ${k}: '${v}',`);
  return `// GENERATED by scripts/gen-colors.mjs from src/design/tokens.css. Do not edit: run npm run gen:colors.
// Only for APIs that need literal colour strings (MapLibre paint, canvas). CSS uses var(--az-*).
export const colors = Object.freeze({
${lines.join('\n')}
});
`;
}

// WCAG 2.x contrast
const hex = h => { h = h.replace('#', ''); if (h.length === 3) h = [...h].map(x => x + x).join(''); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)); };
export function luminance(h) {
  const [r, g, b] = hex(h).map(v => v / 255).map(v => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
export function contrast(a, b) {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

// Pairs the UI actually uses: [foreground, background, minimum, role]
