// Band fills must separate without hue: luminance strictly decreasing from confortable to critique,
// each neighbour pair at least BAND_SEPARATION_MIN apart (contrast ratio between the two fills).
export const BAND_SEPARATION_MIN = 1.4;
export function bandSeparation(tokens = parseTokens()) {
  const f = b => tokens[`--az-band-${b}-fill`];
  return [['confortable', 'tendu'], ['tendu', 'critique']].map(([a, b]) => ({
    pair: `${a}/${b}`, lighter: luminance(f(a)) > luminance(f(b)), ratio: Math.round(contrast(f(a), f(b)) * 100) / 100,
  }));
}

export function contrastReport(tokens = parseTokens()) {
  return CONTRAST_PAIRS.map(([fg, bg, min, role]) => {
    const ratio = contrast(tokens['--az-' + fg], tokens['--az-' + bg]);
    return { fg, bg, role, min, ratio: Math.round(ratio * 100) / 100, ok: ratio >= min };
  });
}
